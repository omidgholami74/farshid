def T(p):
    return "".join(t.text or "" for t in p._p.iter(qn("w:t")))


def find(doc, prefix, required=True):
    for p in doc.paragraphs:
        if T(p).strip().startswith(prefix):
            return p
    if required:
        raise KeyError("anchor not found: %r" % prefix[:60])
    return None


